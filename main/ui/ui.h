#ifndef TANRADIO_MAIN_UI_UI_H
#define TANRADIO_MAIN_UI_UI_H

#include "bsp/input.h"

/**
 * @brief Playback state displayed by the UI.
 */
typedef enum {
    UI_PLAYBACK_STOPPED,
    UI_PLAYBACK_BUFFERING,
    UI_PLAYBACK_PLAYING,
    UI_PLAYBACK_MUTED,
    UI_PLAYBACK_ERROR,
} ui_playback_state_t;

/**
 * @brief Initialize the UI subsystem.
 */
void ui_init(void);

/** Show the welcome screen and wait for Space before services start. */
bool ui_show_welcome(void);

/** Filter a distinct navigation press through the global exit confirmation. */
bool ui_handle_exit_navigation(bsp_input_navigation_key_t key);

/** Start the main screen and status polling after services initialize. */
void ui_start(void);

typedef enum {
    UI_SERVICES_STARTING,
    UI_SERVICES_READY,
    UI_SERVICES_FAILED,
} ui_services_state_t;

/** Publish background service initialization and request a UI frame. */
void ui_set_services_state(ui_services_state_t state);

/**
 * @brief Toggle the display backlight between on and off.
 *
 * Radio playback continues while the display is off.
 */
void ui_toggle_display(void);

/**
 * @brief Handle a BSP navigation event.
 *
 * @param key   Navigation key generated by the BSP.
 * @param state True when pressed, false when released.
 */
void ui_handle_navigation(
    bsp_input_navigation_key_t key,
    bool state);

/**
 * @brief Handle a BSP keyboard event.
 *
 * @param ascii     ASCII character generated by the BSP.
 * @param utf8      UTF-8 representation generated by the BSP.
 * @param modifiers BSP keyboard modifier mask.
 */
void ui_handle_keyboard(
    char ascii,
    const char *utf8,
    uint32_t modifiers);

/**
 * @brief Handle a BSP scancode event.
 *
 * @param scancode PC-compatible keyboard scancode generated by the BSP.
 */
void ui_handle_scancode(
    bsp_input_scancode_t scancode);

/**
 * @brief Set the playback state displayed by the UI.
 *
 * @param state New playback state.
 */
void ui_set_playback_state(ui_playback_state_t state);

/**
 * @brief Get the playback state displayed by the UI.
 *
 * @return Current playback state.
 */
ui_playback_state_t ui_get_playback_state(void);

#endif /* TANRADIO_MAIN_UI_UI_H */
